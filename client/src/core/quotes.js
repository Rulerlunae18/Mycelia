// Короткі думки для екрана входу. Свої власні рядки, без чужих підписів, щоб нікому нічого не приписати.
export const QUOTES = [
  'Кожна велика думка починається з тонкої нитки.',
  'Ліс розмовляє під землею.',
  'Ідеї, як гриби, ростуть мережею.',
  'Усе пов’язане з усім. Лишилося намалювати лінії.',
  'Те, що росте в темряві, потім виносить світло на поверхню.',
  'Не знаєш, з чого почати? Почни з однієї гілки.',
];

export function pickQuote(rng = Math.random) {
  return QUOTES[Math.floor(rng() * QUOTES.length)];
}
